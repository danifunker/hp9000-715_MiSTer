#!/usr/bin/env python3
"""Generate pacputest suites: one assembly routine per (instruction, condition)
group, each running a list of vectors and storing per vector:

    alu/shift suites: result, nullify flag (1 = next insn executed), the
                      PSW carry/borrow bits as a nibble map (idcor %r0)

usage: gen_tests.py SUITE OUTDIR      (suites: alu1, alu2, shift, mem, branch, trap, fp, fpedge, max1)

Writes OUTDIR/gen_SUITE.S and OUTDIR/gen_SUITE.c. Candidate instructions
are assembled once on their own first; any (mnemonic, condition) GNU as
rejects is dropped, so the condition tables can be generous.
"""
import json
import os
import random
import subprocess
import sys
import tempfile

AS = os.environ.get("HPPA_AS", "hppa-linux-gnu-as")

SPECIALS = [0x00000000, 0x00000001, 0x00000002, 0x7FFFFFFF, 0x80000000,
            0xFFFFFFFF, 0xFFFFFFFE, 0x0000FFFF, 0xFFFF0000, 0x55555555,
            0xAAAAAAAA, 0x0F0F0F0F, 0x99999999, 0x12345678, 0x00008000,
            0x00010000, 0x80000001, 0x40000000, 0x09090909, 0x00FF00FF]

COND_ADD = ["", "=", "<", "<=", "nuv", "znv", "sv", "od", "tr", "<>", ">=", ">",
            "uv", "vnz", "nsv", "ev"]
COND_CMP = ["", "=", "<", "<=", "<<", "<<=", "sv", "od", "tr", "<>", ">=", ">",
            ">>=", ">>", "nsv", "ev"]
COND_LOG = ["", "=", "<", "<=", "od", "tr", "<>", ">=", ">", "ev"]
COND_UNIT = ["", "sbz", "shz", "sdc", "sbc", "shc", "tr", "nbz", "nhz", "ndc", "nbc", "nhc"]
COND_SHIFT = ["", "=", "<", "od", "tr", "<>", ">=", "ev"]

N_PLAIN = 40      # vectors for the unconditional form
N_COND = 10       # vectors per condition


def operand_pairs(rng, n):
    """Mix of special values, equal pairs and random words."""
    out = []
    for i in range(n):
        k = rng.random()
        if k < 0.35:
            a, b = rng.choice(SPECIALS), rng.choice(SPECIALS)
        elif k < 0.45:
            a = rng.getrandbits(32)
            b = a
        elif k < 0.6:
            a = rng.getrandbits(32)
            b = rng.choice(SPECIALS)
        else:
            a, b = rng.getrandbits(32), rng.getrandbits(32)
        out.append((a, b))
    return out


def li(reg, val):
    val &= 0xFFFFFFFF
    return ["\tldil\tL%%0x%08x, %%r%d" % (val, reg),
            "\tldo\tR%%0x%08x(%%r%d), %%r%d" % (val, reg, reg)]


def check_assembles(lines):
    """Return the set of indices of `lines` that GNU as rejects."""
    with tempfile.TemporaryDirectory() as d:
        src = os.path.join(d, "t.s")
        with open(src, "w") as f:
            f.write("\t.text\n")
            for ln in lines:
                f.write(ln + "\n")
        r = subprocess.run([AS, "-o", os.path.join(d, "t.o"), src],
                           capture_output=True, text=True)
    bad = set()
    for msg in r.stderr.splitlines():
        # "t.s:LINE: Error: ..."
        parts = msg.split(":")
        if len(parts) > 2 and "Error" in msg:
            try:
                bad.add(int(parts[1]) - 2)
            except ValueError:
                pass
    return bad


def filter_valid(cands):
    """cands: list of (key, insn_text). Keep those GNU as accepts."""
    bad = check_assembles([c[1] for c in cands])
    return [c for i, c in enumerate(cands) if i not in bad]


class Suite:
    def __init__(self, name):
        self.name = name
        self.groups = []      # (gname, symbol, vectors, words, body_lines)
        self.inputs = []      # per group: the operands of each vector (JSON sidecar)
        self.prologue = []    # helper routines emitted before the groups
        self.setup = []       # lines run at the start of every group routine

    def add(self, gname, vectors, words, body, inputs=None):
        sym = "tg_%s_%d" % (self.name, len(self.groups))
        self.groups.append((gname, sym, vectors, words, body))
        self.inputs.append({"group": gname, "inputs": inputs or []})

    def write(self, outdir):
        s = []
        s.append("/* generated by tests/cpu/gen_tests.py -- do not edit */")
        s.append("\t.text")
        s.extend(self.prologue)
        for gname, sym, vectors, words, body in self.groups:
            s.append("")
            s.append("/* %s: %d vectors x %d words */" % (gname, vectors, words))
            s.append("\t.align\t4")
            s.append("\t.globl\t%s" % sym)
            s.append("%s:" % sym)
            # save every callee-saved register (r3..r18: tests may touch any
            # of them, e.g. the shadow-register test); r9 = output pointer
            s.append("\tldo\t128(%sp), %sp")
            for i, r in enumerate(range(3, 19)):
                s.append("\tstw\t%%r%d, -%d(%%sp)" % (r, 128 - 4 * i))
            s.append("\tcopy\t%r26, %r9")
            s.extend(self.setup)
            s.extend(body)
            for i, r in enumerate(range(3, 19)):
                s.append("\tldw\t-%d(%%sp), %%r%d" % (128 - 4 * i, r))
            s.append("\tbv\t%r0(%rp)")
            s.append("\tldo\t-128(%sp), %sp")
        with open(os.path.join(outdir, "gen_%s.S" % self.name), "w") as f:
            f.write("\n".join(s) + "\n")

        c = ['/* generated by tests/cpu/gen_tests.py -- do not edit */',
             '#include "pacputest.h"', '']
        for gname, sym, *_ in self.groups:
            c.append("void %s(unsigned *out);" % sym)
        c.append("")
        c.append('const char tsuite_name[] = "%s";' % self.name)
        c.append("const struct tgroup tgroups[] = {")
        for gname, sym, vectors, words, body in self.groups:
            c.append('\t{ "%s", %s, %d, %d },' % (gname.replace('"', '\\"'), sym, vectors, words))
        c.append("};")
        c.append("const int tgroup_count = %d;" % len(self.groups))
        with open(os.path.join(outdir, "gen_%s.c" % self.name), "w") as f:
            f.write("\n".join(c) + "\n")
        with open(os.path.join(outdir, "gen_%s.json" % self.name), "w") as f:
            json.dump(self.inputs, f, indent=0)


# ---------------------------------------------------------------------------
# Vector bodies. Registers: r3 = a, r4 = b, r5 = t, r6 = nullify flag,
# r7 = carry map, r9 = output pointer, r10 = SAR value.
# ---------------------------------------------------------------------------
CARRY_CLEAR = ["\tadd\t%r0, %r0, %r0"]        # every C/B bit 0
CARRY_SET = ["\tsub\t%r0, %r0, %r0"]          # 0 + ~0 + 1: every C/B bit 1


def vec_tail():
    return ["\tldi\t1, %r6",                  # skipped if the insn nullifies
            "\tidcor\t%r0, %r7",               # C/B bits -> 0x6 per set nibble
            "\tstw,ma\t%r5, 4(%r9)",
            "\tstw,ma\t%r6, 4(%r9)",
            "\tstw,ma\t%r7, 4(%r9)"]


ALU1 = {"add", "addl", "addc", "sh1add", "sh2add", "sh3add", "sh1addl", "sh2addl",
        "sh3addl", "sub", "subb", "comclr", "addi", "subi", "comiclr"}


def gen_alu1(rng):
    return gen_alu(rng, "alu1", lambda m: m in ALU1, longimm=False)


def gen_alu2(rng):
    return gen_alu(rng, "alu2", lambda m: m not in ALU1, longimm=True)


def gen_alu(rng, name, want, longimm):
    suite = Suite(name)
    three = [("add", COND_ADD), ("addl", COND_ADD), ("addc", COND_ADD),
             ("sh1add", COND_ADD), ("sh2add", COND_ADD), ("sh3add", COND_ADD),
             ("sh1addl", COND_ADD), ("sh2addl", COND_ADD), ("sh3addl", COND_ADD),
             ("sub", COND_CMP), ("subb", COND_CMP), ("comclr", COND_CMP),
             ("and", COND_LOG), ("andcm", COND_LOG), ("or", COND_LOG), ("xor", COND_LOG),
             ("uxor", COND_UNIT), ("uaddcm", COND_UNIT), ("uaddcmt", COND_UNIT)]
    cands = []
    for m, conds in three:
        for c in conds:
            mn = m + ("," + c if c else "")
            cands.append(((m, c), "\t%s\t%%r3, %%r4, %%r5" % mn))
    # unary decimal correct
    for m in ("dcor", "idcor"):
        for c in COND_UNIT:
            mn = m + ("," + c if c else "")
            cands.append(((m, c), "\t%s\t%%r3, %%r5" % mn))
    # immediates
    for m, conds in (("addi", COND_ADD), ("subi", COND_CMP), ("comiclr", COND_CMP)):
        for c in conds:
            mn = m + ("," + c if c else "")
            cands.append(((m, c), "\t%s\t5, %%r3, %%r5" % mn))
    # uaddcmt with a condition TRAPS (conditional trap) instead of nullifying:
    # that belongs to the trap suite, which installs an interruption handler.
    valid = [v for v in filter_valid(cands) if want(v[0][0])
             and not (v[0][0] == "uaddcmt" and v[0][1])]
    for (m, c), _ in valid:
        n = N_PLAIN if c == "" else N_COND
        # ops with a carry-in get a group per preset; the rest get a random
        # preset per vector, so an op that must leave C/B alone is seen to
        carry_variants = [("", None)]
        if m in ("addc", "subb", "dcor", "idcor"):
            carry_variants = [(".c0", CARRY_CLEAR), (".c1", CARRY_SET)]
        for suffix, fixed_carry in carry_variants:
            body, ins = [], []
            for a, b in operand_pairs(rng, n):
                carry = fixed_carry or rng.choice([CARRY_CLEAR, CARRY_SET])
                vin = {"a": a, "b": b, "carry": 1 if carry is CARRY_SET else 0}
                ins.append(vin)
                body += li(3, a) + li(4, b)
                body += carry
                body.append("\tldi\t0, %r6")
                mn = m + ("," + c if c else "")
                if m in ("addi", "subi", "comiclr"):
                    imm = rng.choice([0, 1, -1, 1023, -1024, rng.randint(-1024, 1023)])
                    vin["imm"] = imm
                    body.append("\t%s\t%d, %%r3, %%r5" % (mn, imm))
                elif m in ("dcor", "idcor"):
                    body.append("\t%s\t%%r3, %%r5" % mn)
                else:
                    body.append("\t%s\t%%r3, %%r4, %%r5" % mn)
                body += vec_tail()
            suite.add("%s%s%s" % (m, "," + c if c else "", suffix), n, 3, body, ins)
    if longimm:
        gen_ds(rng, suite)
    # long immediates: ldil / ldo / addil (no condition, no nullify)
    for m in (("ldil", "addil", "ldo") if longimm else ()):
        body, ins = [], []
        for a, _b in operand_pairs(rng, N_PLAIN):
            carry = rng.choice([CARRY_CLEAR, CARRY_SET])
            body += li(3, a) + carry
            body.append("\tldi\t0, %r6")
            imm = rng.getrandbits(32)
            vin = {"a": a, "imm": imm, "carry": 1 if carry is CARRY_SET else 0}
            ins.append(vin)
            if m == "ldil":
                body.append("\tldil\tL%%0x%08x, %%r5" % imm)
            elif m == "addil":
                body.append("\taddil\tL%%0x%08x, %%r3" % imm)
                body.append("\tcopy\t%r1, %r5")
            else:
                d = rng.randint(-8192, 8191)
                vin["imm"] = d
                body.append("\tldo\t%d(%%r3), %%r5" % d)
            body += vec_tail()
        suite.add(m, N_PLAIN, 3, body, ins)
    return suite


def gen_ds(rng, suite):
    """DIVIDE STEP groups for alu2: every compare condition, with PSW V
    forced to 0 or 1 first. `ds %r0,%r11,%r0` sets V regardless of its old
    value: r11 = 0x80000000 gives V = 1, r11 = 1 gives V = 0 (and C/B = 0).
    V afterwards is read from the IPSW of a break (PA PSW bit 14)."""
    for cond in COND_CMP:
        for vset in (0, 1):
            body, ins = [], []
            n = N_PLAIN if cond == "" else 6
            for a, b in operand_pairs(rng, n):
                carry = rng.choice([CARRY_CLEAR, CARRY_SET])
                # C/B{0} is shifted in, so clear it first; then the DS forces V
                body += CARRY_CLEAR + li(11, 0x80000000 if vset else 1)
                body.append("\tds\t%r0, %r11, %r0")
                if carry is CARRY_SET:
                    body += CARRY_SET
                body += li(3, a) + li(4, b)
                body.append("\tldi\t0, %r6")
                body.append("\tds%s\t%%r3, %%r4, %%r5" % ("," + cond if cond else ""))
                body += ["\tldi\t1, %r6", "\tidcor\t%r0, %r7", "\tbreak\t0, 0"]
                body += li(12, TRAPLOG)
                body += ["\tldw\t16(%r12), %r8", "\textru\t%r8, 14, 1, %r8",
                         "\tstw,ma\t%r5, 4(%r9)", "\tstw,ma\t%r6, 4(%r9)",
                         "\tstw,ma\t%r7, 4(%r9)", "\tstw,ma\t%r8, 4(%r9)"]
                ins.append({"a": a, "b": b, "v": vset,
                            "carry": 1 if carry is CARRY_SET else 0})
            suite.add("ds%s.v%d" % ("," + cond if cond else "", vset), n, 4, body, ins)


def gen_shift(rng):
    suite = Suite("shift")
    cands = []
    for c in COND_SHIFT:
        sfx = ("," + c if c else "")
        cands += [(("shd", c), "\tshd%s\t%%r3, %%r4, 7, %%r5" % sfx),
                  (("vshd", c), "\tvshd%s\t%%r3, %%r4, %%r5" % sfx),
                  (("extru", c), "\textru%s\t%%r3, 15, 8, %%r5" % sfx),
                  (("extrs", c), "\textrs%s\t%%r3, 15, 8, %%r5" % sfx),
                  (("vextru", c), "\tvextru%s\t%%r3, 8, %%r5" % sfx),
                  (("vextrs", c), "\tvextrs%s\t%%r3, 8, %%r5" % sfx),
                  (("zdep", c), "\tzdep%s\t%%r3, 15, 8, %%r5" % sfx),
                  (("dep", c), "\tdep%s\t%%r3, 15, 8, %%r5" % sfx),
                  (("zvdep", c), "\tzvdep%s\t%%r3, 8, %%r5" % sfx),
                  (("vdep", c), "\tvdep%s\t%%r3, 8, %%r5" % sfx),
                  (("depi", c), "\tdepi%s\t5, 15, 8, %%r5" % sfx),
                  (("zdepi", c), "\tzdepi%s\t5, 15, 8, %%r5" % sfx),
                  (("vdepi", c), "\tvdepi%s\t5, 8, %%r5" % sfx),
                  (("zvdepi", c), "\tzvdepi%s\t5, 8, %%r5" % sfx)]
    valid = filter_valid(cands)
    for (m, c), _ in valid:
        n = N_PLAIN if c == "" else N_COND
        sfx = ("," + c if c else "")
        body, ins = [], []
        for a, b in operand_pairs(rng, n):
            pos = rng.randint(0, 31)
            ln = rng.randint(1, pos + 1)
            sar = rng.randint(0, 31)
            vln = rng.randint(1, 32)
            imm = rng.randint(-16, 15)
            carry = rng.choice([CARRY_CLEAR, CARRY_SET])
            ins.append({"a": a, "b": b, "pos": pos, "len": ln, "sar": sar,
                        "vlen": vln, "imm": imm, "carry": 1 if carry is CARRY_SET else 0})
            body += li(3, a) + li(4, b) + li(5, b)      # r5 = b for deposits
            body += carry
            body += li(10, sar)
            body.append("\tmtsar\t%r10")
            body.append("\tldi\t0, %r6")
            if m == "shd":
                body.append("\tshd%s\t%%r3, %%r4, %d, %%r5" % (sfx, sar))
            elif m == "vshd":
                body.append("\tvshd%s\t%%r3, %%r4, %%r5" % sfx)
            elif m in ("extru", "extrs", "zdep", "dep"):
                body.append("\t%s%s\t%%r3, %d, %d, %%r5" % (m, sfx, pos, ln))
            elif m in ("vextru", "vextrs", "zvdep", "vdep"):
                body.append("\t%s%s\t%%r3, %d, %%r5" % (m, sfx, vln))
            elif m in ("depi", "zdepi"):
                body.append("\t%s%s\t%d, %d, %d, %%r5" % (m, sfx, imm, pos, ln))
            else:   # vdepi, zvdepi
                body.append("\t%s%s\t%d, %d, %%r5" % (m, sfx, imm, vln))
            body += vec_tail()
        suite.add("%s%s" % (m, sfx), n, 3, body, ins)
    # mtsar / mfctl %sar round trip
    body, ins = [], []
    for a, _b in operand_pairs(rng, N_PLAIN):
        carry = rng.choice([CARRY_CLEAR, CARRY_SET])
        ins.append({"a": a, "carry": 1 if carry is CARRY_SET else 0})
        body += li(3, a) + carry
        body.append("\tmtsar\t%r3")
        body.append("\tldi\t0, %r6")
        body.append("\tmfctl\t%sar, %r5")
        body += vec_tail()
    suite.add("mtsar/mfctl", N_PLAIN, 3, body, ins)
    return suite


# ---------------------------------------------------------------------------
# mem: every load/store addressing form. A 64-byte window at AREA is filled
# with a per-vector pattern by mem_fill (link in r13), r3 = base, r4 = index,
# r5 = store value. Each vector stores: r5, r3 - AREA (base after any
# modify), then the 16 words of the window.
# ---------------------------------------------------------------------------
AREA = 0x00100000
MEM_WORDS = 2 + 16

MEM_FILL = [
    "\t.align\t4",
    "mem_fill_%(s)s:",                      # r12 = seed; fills AREA..AREA+63
    "\tldil\tL%%0x%(area)08x, %%r10" ,
    "\tldo\tR%%0x%(area)08x(%%r10), %%r10",
    "\tldi\t16, %%r11",
    "1:\tstw,ma\t%%r12, 4(%%r10)",
    "\tshd\t%%r12, %%r12, 25, %%r12",        # rotate the seed
    "\taddib,>\t-1, %%r11, 1b",
    "\taddi\t0x5b, %%r12, %%r12",
    "\tbv,n\t%%r0(%%r13)",
]


def mem_tail(suite):
    t = ["\tstw,ma\t%r5, 4(%r9)",
         "\tldil\tL%%0x%08x, %%r10" % AREA,
         "\tldo\tR%%0x%08x(%%r10), %%r10" % AREA,
         "\tsub\t%r3, %r10, %r11",
         "\tstw,ma\t%r11, 4(%r9)"]
    for i in range(16):
        t += ["\tldw\t%d(%%r10), %%r11" % (4 * i), "\tstw,ma\t%r11, 4(%r9)"]
    return t


def gen_mem(rng):
    suite = Suite("mem")
    suite.prologue = [l % {"s": "mem", "area": AREA} for l in MEM_FILL]
    N = 12
    forms = []
    for m, size in (("ldw", 4), ("ldh", 2), ("ldb", 1), ("stw", 4), ("sth", 2), ("stb", 1)):
        forms.append((m, "long", size, ""))
    for m in ("ldwm", "stwm"):
        forms.append((m, "longm", 4, ""))
    for m, size in (("ldwx", 4), ("ldhx", 2), ("ldbx", 1)):
        for c in ("", ",s", ",m", ",sm"):
            forms.append((m, "idx", size, c))
    for m, size in (("ldws", 4), ("ldhs", 2), ("ldbs", 1), ("stws", 4), ("sths", 2), ("stbs", 1)):
        for c in ("", ",ma", ",mb"):
            forms.append((m, "short", size, c))
    for c in (",b", ",e", ",b,m", ",e,m"):
        forms.append(("stbys", "stbys", 1, c))
    forms.append(("ldcws", "ldcw", 4, ""))
    forms.append(("ldcwx", "ldcwx", 4, ""))
    forms.append(("ldcwx", "ldcwx", 4, ",s"))
    forms.append(("ldwax", "idx", 4, ""))
    forms.append(("ldwax", "idx", 4, ",s"))
    for m, kind, size, c in forms:
        body, ins = [], []
        for v in range(N):
            seed = rng.getrandbits(32)
            val = rng.getrandbits(32)
            if kind in ("ldcw", "ldcwx"):
                off = rng.choice([16, 32])                 # 16-byte aligned
            elif kind == "stbys":
                off = 24 + rng.randint(0, 3)               # any byte offset
            else:
                off = 24 + size * rng.randint(0, 4 // size if size < 4 else 1)
            body += li(12, seed)
            body.append("\tb,l\tmem_fill_mem, %r13")
            body.append("\tnop")
            body += li(3, AREA + off) + li(5, val)
            d = 0
            idx = 0
            if kind == "long":
                d = size * rng.randint(-4 // size if size < 4 else -2, 2)
                op = ("\t%s\t%d(%%r3), %%r5" % (m, d)) if m.startswith("ld") else \
                     ("\t%s\t%%r5, %d(%%r3)" % (m, d))
            elif kind == "longm":
                d = rng.choice([-8, -4, 4, 8])
                op = ("\t%s\t%d(%%r3), %%r5" % (m, d)) if m.startswith("ld") else \
                     ("\t%s\t%%r5, %d(%%r3)" % (m, d))
            elif kind in ("idx", "ldcwx"):
                idx = rng.randint(-2, 2)
                if "s" not in c and kind != "ldcwx":
                    idx *= size
                if kind == "ldcwx":
                    idx = 0 if ",s" in c else rng.choice([0, 16, -16])
                body += li(4, idx)
                op = "\t%s%s\t%%r4(%%r3), %%r5" % (m, c)
            elif kind == "short":
                d = size * rng.randint(-2, 2)
                op = ("\t%s%s\t%d(%%r3), %%r5" % (m, c, d)) if m.startswith("ld") else \
                     ("\t%s%s\t%%r5, %d(%%r3)" % (m, c, d))
            elif kind == "stbys":
                op = "\tstbys%s\t%%r5, 0(%%r3)" % c
            else:   # ldcw
                op = "\tldcws\t0(%r3), %r5"
            body.append(op)
            body += mem_tail(suite)
            ins.append({"seed": seed, "val": val, "off": off, "disp": d, "index": idx})
        suite.add("%s%s" % (m, c), N, MEM_WORDS, body, ins)
    return suite


# ---------------------------------------------------------------------------
# branch: every conditional branch, both directions, with and without ,n.
# r6 collects which instructions ran: bit 0 delay slot, bit 1 fall-through,
# bit 2 taken path. Stored: r6, r3, r4 (addb/movb modify them).
# ---------------------------------------------------------------------------
def gen_branch(rng):
    suite = Suite("branch")
    N = 8
    kinds = []
    for c in COND_CMP[1:]:
        kinds.append(("comb", c, "\tcomb,%s%%(n)s\t%%%%r3, %%%%r4, %%(t)s" % c))
        kinds.append(("comib", c, "\tcomib,%s%%(n)s\t%%(imm)d, %%%%r4, %%(t)s" % c))
    for c in COND_ADD[1:]:
        kinds.append(("addb", c, "\taddb,%s%%(n)s\t%%%%r3, %%%%r4, %%(t)s" % c))
        kinds.append(("addib", c, "\taddib,%s%%(n)s\t%%(imm)d, %%%%r4, %%(t)s" % c))
    for c in COND_SHIFT[1:]:
        kinds.append(("movb", c, "\tmovb,%s%%(n)s\t%%%%r3, %%%%r4, %%(t)s" % c))
        kinds.append(("movib", c, "\tmovib,%s%%(n)s\t%%(imm)d, %%%%r4, %%(t)s" % c))
    for c in ("<", ">="):
        kinds.append(("bb", c, "\tbb,%s%%(n)s\t%%%%r3, %%(bit)d, %%(t)s" % c))
        kinds.append(("bvb", c, "\tbvb,%s%%(n)s\t%%%%r3, %%(t)s" % c))
    probe = [((m, c), tpl % {"n": "", "t": ".+8", "imm": 5, "bit": 3}) for m, c, tpl in kinds]
    ok = {k for k, _ in filter_valid(probe)}
    for m, c, tpl in kinds:
        if (m, c) not in ok:
            continue
        for nul in ("", ",n"):
            for direction in ("f", "b"):
                body, ins = [], []
                for v in range(N):
                    a, b = operand_pairs(rng, 1)[0]
                    if rng.random() < 0.3:
                        b = rng.choice([0, 1, -1 & 0xFFFFFFFF, 2, 0x7FFFFFFF])
                    imm = rng.randint(-16, 15)
                    bit = rng.randint(0, 31)
                    sar = rng.randint(0, 31)
                    body += li(3, a) + li(4, b) + li(10, sar)
                    body.append("\tmtsar\t%r10")
                    body.append("\tldi\t0, %r6")
                    f = {"n": nul, "imm": imm, "bit": bit}
                    if direction == "f":
                        f["t"] = "1f"
                        body += [tpl % f,
                                 "\tdepi\t-1, 31, 1, %r6",
                                 "\tdepi\t-1, 30, 1, %r6",
                                 "\tb,n\t2f",
                                 "1:\tdepi\t-1, 29, 1, %r6",
                                 "2:"]
                    else:
                        f["t"] = "1b"
                        body += ["\tb,n\t3f",
                                 "1:\tdepi\t-1, 29, 1, %r6",
                                 "\tb,n\t2f",
                                 "3:" + tpl % f,
                                 "\tdepi\t-1, 31, 1, %r6",
                                 "\tdepi\t-1, 30, 1, %r6",
                                 "2:"]
                    body += ["\tstw,ma\t%r6, 4(%r9)",
                             "\tstw,ma\t%r3, 4(%r9)",
                             "\tstw,ma\t%r4, 4(%r9)"]
                    ins.append({"a": a, "b": b, "imm": imm, "bit": bit, "sar": sar})
                suite.add("%s,%s%s.%s" % (m, c, nul, direction), N, 3, body, ins)
    # unconditional and computed branches: r6 path bits as above, plus the
    # link register (absolute address; the ROM image is the same everywhere)
    def uncond(name, setup, insn, link):
        body, ins = [], []
        for v in range(4):
            body += setup + ["\tldi\t0, %r6", "\tldi\t0, %s" % link if link else "\tnop",
                             insn,
                             "\tdepi\t-1, 31, 1, %r6",
                             "\tdepi\t-1, 30, 1, %r6",
                             "\tb,n\t2f",
                             "1:\tdepi\t-1, 29, 1, %r6",
                             "2:\tstw,ma\t%r6, 4(%r9)",
                             "\tstw,ma\t%s, 4(%%r9)" % (link or "%r0"),
                             "\tstw,ma\t%r0, 4(%r9)"]
            ins.append({})
        suite.add(name, 4, 3, body, ins)
    for nul in ("", ",n"):
        uncond("b,l%s" % nul, [], "\tb,l%s\t1f, %%r11" % nul, "%r11")
        uncond("bl.r0%s" % nul, [], "\tb,l%s\t1f, %%r0" % nul, None)
        uncond("bv%s" % nul, ["\tldil\tL%1f, %r3", "\tldo\tR%1f(%r3), %r3", "\tldi\t0, %r4"],
               "\tbv%s\t%%r4(%%r3)" % nul, None)
        uncond("be%s" % nul, ["\tmtsp\t%r0, %sr4", "\tldil\tL%1f, %r3", "\tldo\tR%1f(%r3), %r3"],
               "\tbe%s\t0(%%sr4, %%r3)" % nul, None)
        uncond("ble%s" % nul, ["\tmtsp\t%r0, %sr4", "\tldil\tL%1f, %r3", "\tldo\tR%1f(%r3), %r3"],
               "\tble%s\t0(%%sr4, %%r3)" % nul, "%r31")
    # blr: target = (address of blr) + 8 + 8*index; slots of two insns each
    body, ins = [], []
    for idx in range(4):
        body += ["\tldi\t%d, %%r4" % idx, "\tldi\t0, %r6",
                 "\tblr\t%r4, %r11",
                 "\tdepi\t-1, 31, 1, %r6"]
        for k in range(4):
            body += ["\tb\t2f", "\tdepi\t-1, %d, 1, %%r6" % (27 - k)]
        body += ["2:\tstw,ma\t%r6, 4(%r9)", "\tstw,ma\t%r11, 4(%r9)", "\tstw,ma\t%r4, 4(%r9)"]
        ins.append({"index": idx})
    suite.add("blr", 4, 3, body, ins)
    # a branch in the delay slot of a branch: executes B1, B2, T1, then T2
    body = ["\tldi\t0, %r6",
            "\tb\t1f",
            "\tb\t2f",
            "\tdepi\t-1, 31, 1, %r6",       # never (fall-through of B1)
            "1:\tdepi\t-1, 30, 1, %r6",      # T1: runs once
            "\tdepi\t-1, 29, 1, %r6",        # never (T1+4)
            "2:\tdepi\t-1, 28, 1, %r6",      # T2
            "\tstw,ma\t%r6, 4(%r9)", "\tstw,ma\t%r0, 4(%r9)", "\tstw,ma\t%r0, 4(%r9)"]
    suite.add("branch-in-delay-slot", 1, 3, body, [{}])
    # a nullified branch does not branch; a nullified nullifier does not nullify
    body = ["\tldi\t0, %r6",
            "\tadd,tr\t%r0, %r0, %r0",       # nullifies the next insn
            "\tb\t1f",                        # nullified: no branch
            "\tdepi\t-1, 31, 1, %r6",        # runs
            "\tadd,tr\t%r0, %r0, %r0",
            "\tadd,tr\t%r0, %r0, %r0",       # nullified, so it nullifies nothing
            "\tdepi\t-1, 30, 1, %r6",        # runs
            "1:\tdepi\t-1, 29, 1, %r6",
            "\tstw,ma\t%r6, 4(%r9)", "\tstw,ma\t%r0, 4(%r9)", "\tstw,ma\t%r0, 4(%r9)"]
    suite.add("nullify-chain", 1, 3, body, [{}])
    return suite

# ---------------------------------------------------------------------------
# trap: interruptions, through src/ivt.S. Each vector clears the trap log,
# preloads r5 with a sentinel (a trapping insn must not write its target),
# runs the insn, then stores: r5, r6 (next insn ran), and the log's
# number, IIR, ISR, IOR, IPSW and IIAOQ front.
# ---------------------------------------------------------------------------
TRAPLOG = 0x000F0000
SENTINEL = 0xDEADBEEF
TRAP_WORDS = 8


def trap_vector(insn_lines, setup=()):
    b = li(12, TRAPLOG)
    for i in range(7):
        b.append("\tstw\t%%r0, %d(%%r12)" % (4 * i))
    b += list(setup)
    b += li(5, SENTINEL)
    b += CARRY_CLEAR
    b.append("\tldi\t0, %r6")
    b += insn_lines
    b.append("\tldi\t1, %r6")
    b += ["\tstw,ma\t%r5, 4(%r9)", "\tstw,ma\t%r6, 4(%r9)"]
    for i in (0, 1, 2, 3, 4, 5):
        b += ["\tldw\t%d(%%r12), %%r11" % (4 * i), "\tstw,ma\t%r11, 4(%r9)"]
    return b


def gen_trap(rng):
    suite = Suite("trap")
    N = 12
    def group(name, make, n=N):
        body, ins = [], []
        for v in range(n):
            lines, setup, vin = make(v)
            body += trap_vector(lines, setup)
            ins.append(vin)
        suite.add(name, n, TRAP_WORDS, body, ins)

    def ops(v):
        if v % 3 == 0:      # steer a third of the vectors at overflow
            return rng.choice([(0x7FFFFFFF, 1), (0x80000000, 0xFFFFFFFF),
                               (0x40000000, 0x40000000), (0x80000000, 0x80000000)])
        return operand_pairs(rng, 1)[0]
    # overflow traps (trap 12)
    for m in ("addo", "addco", "sh1addo", "sh2addo", "sh3addo", "subo", "subbo"):
        def mk(v, m=m):
            a, b = ops(v)
            return (["\t%s\t%%r3, %%r4, %%r5" % m], li(3, a) + li(4, b), {"a": a, "b": b})
        group(m, mk)
    for m in ("addio", "subio"):
        def mk(v, m=m):
            a, _ = ops(v)
            imm = rng.choice([1, -1, 1023, -1024, rng.randint(-1024, 1023)])
            return (["\t%s\t%d, %%r3, %%r5" % (m, imm)], li(3, a), {"a": a, "imm": imm})
        group(m, mk)
    # conditional traps (trap 13), every condition
    cands = []
    for c in COND_CMP[1:]:
        cands += [(("subt", c), "\tsubt,%s\t%%r3, %%r4, %%r5" % c),
                  (("subto", c), "\tsubto,%s\t%%r3, %%r4, %%r5" % c)]
    for c in COND_ADD[1:]:
        cands += [(("addit", c), "\taddit,%s\t5, %%r3, %%r5" % c),
                  (("addito", c), "\taddito,%s\t5, %%r3, %%r5" % c)]
    for c in COND_UNIT[1:]:
        cands.append((("uaddcmt", c), "\tuaddcmt,%s\t%%r3, %%r4, %%r5" % c))
    for (m, c), _ in filter_valid(cands):
        def mk(v, m=m, c=c):
            a, b = ops(v)
            imm = rng.randint(-1024, 1023)
            if m.startswith("addit"):
                return (["\t%s,%s\t%d, %%r3, %%r5" % (m, c, imm)], li(3, a), {"a": a, "imm": imm})
            return (["\t%s,%s\t%%r3, %%r4, %%r5" % (m, c)], li(3, a) + li(4, b), {"a": a, "b": b})
        group("%s,%s" % (m, c), mk, 6)
    # break (trap 9): IIR carries the immediates
    def mkbrk(v):
        i5, i13 = rng.randint(0, 31), rng.randint(0, 8191)
        return (["\tbreak\t%d, %d" % (i5, i13)], (), {"im5": i5, "im13": i13})
    group("break", mkbrk, 4)
    # illegal instructions (trap 8): major opcodes PA 1.1 does not define
    illegal = [0x07 << 26, 0x1D << 26 | 0x1234, 0x1F << 26, 0x14 << 26 | 0x00210000,
               0x1C << 26 | 0x00210000, 0x3C << 26, 0x3D << 26, 0x3F << 26]
    def mkill(v):
        w = illegal[v]
        return (["\t.word\t0x%08x" % w], (), {"word": w})
    group("illegal", mkill, len(illegal))
    # unaligned data references (trap 28 / 18): IOR = the address
    un = [("ldw", 2), ("ldw", 1), ("ldh", 1), ("stw", 2), ("sth", 3), ("ldwm", 2),
          ("stwm", 1), ("ldcws", 4), ("ldcws", 8)]
    def mkun(v):
        m, off = un[v]
        base = AREA + 32 + off
        if m.startswith("st"):
            ln = "\t%s\t%%r4, 0(%%r3)" % m
        elif m == "ldwm":
            ln = "\tldwm\t4(%r3), %r5"
        else:
            ln = "\t%s\t0(%%r3), %%r5" % m
        return ([ln], li(3, base) + li(4, 0x12345678), {"insn": m, "addr": base})
    group("unaligned", mkun, len(un))
    # shadow registers: RFIR must give back r1 r8 r9 r16 r17 r24 r25
    body = []
    vals = {1: 0x11111111, 8: 0x88888888, 16: 0x16161616, 17: 0x17171717,
            24: 0x24242424, 25: 0x25252525}
    body += li(12, TRAPLOG)
    for r, v in vals.items():
        body += li(r, v)
    body += ["\tbreak\t1, 2"]
    for r in vals:
        body.append("\tstw,ma\t%%r%d, 4(%%r9)" % r)
    body += ["\tldw\t0(%r12), %r11", "\tstw,ma\t%r11, 4(%r9)",
             "\tldw\t28(%r12), %r11", "\tstw,ma\t%r11, 4(%r9)"]
    suite.add("shadow-regs", 1, TRAP_WORDS, body, [{}])
    return suite

# ---------------------------------------------------------------------------
# fp / fpedge: floating point. Operands come from a per-group table in the
# ROM (r3 -> vector's entry: a, b, sentinel for the target), the status
# register (fr0) is loaded per vector (rounding mode, no enables, no
# flags). Stored per vector: target (64 bits, both halves of fr6), status.
# `fp` keeps every operand and result finite, normal and far from the
# overflow/underflow thresholds (QEMU's softfloat is a sound reference
# there); `fpedge` holds zeros, infinities, NaNs (PA-RISC's quiet/signalling
# convention), denormals, overflow and underflow -- the cases where a real
# PA7100LC may take an unimplemented-exception trap (docs/design/cpu.md).
# ---------------------------------------------------------------------------
import struct

FP_WORDS = 4      # target (2 words), status, pad: fstds needs 8-byte alignment
RM_NAMES = ["rn", "rz", "rp", "rm"]


def d2w(x):
    return struct.unpack(">Q", struct.pack(">d", x))[0]


def f2w(x):
    return struct.unpack(">I", struct.pack(">f", x))[0]


def rand_normal_double(rng, lo=-30, hi=30):
    return rng.choice([-1, 1]) * rng.uniform(1.0, 2.0) * (2.0 ** rng.randint(lo, hi))


def fp_edge_values(sgl):
    if sgl:
        return [0x00000000, 0x80000000, 0x7F800000, 0xFF800000,       # +-0, +-inf
                0x7FC00000, 0x7FA00000, 0x7F800001, 0xFFFFFFFF,       # NaNs, both senses
                0x00000001, 0x007FFFFF, 0x80400000,                   # denormals
                0x7F7FFFFF, 0x00800000, 0x3F800000, 0xBF800000]       # max, min normal, +-1
    return [0x0, 0x8000000000000000, 0x7FF0000000000000, 0xFFF0000000000000,
            0x7FF8000000000000, 0x7FF4000000000000, 0x7FF0000000000001, 0xFFFFFFFFFFFFFFFF,
            0x0000000000000001, 0x000FFFFFFFFFFFFF, 0x8008000000000000,
            0x7FEFFFFFFFFFFFFF, 0x0010000000000000, 0x3FF0000000000000, 0xBFF0000000000000]


class FpGroup:
    """Builds one group: a data table plus the per-vector code."""
    def __init__(self, suite, name):
        self.suite, self.name = suite, name
        self.body, self.data, self.ins = [], [], []
        self.label = "fpt_%s_%d" % (suite.name, len(suite.groups))

    def vector(self, rm, a, b, sentinel, op_lines, sgl_load, vin):
        k = len(self.ins)
        # entry: status, a, b, sentinel (FP loads have 5-bit displacements
        # in PA 1.1, so r3 -> entry and r4 -> entry + 16)
        self.data += ["\t.word\t0x%08x, 0" % (rm << 9),
                      "\t.word\t0x%08x, 0x%08x" % (a >> 32, a & 0xFFFFFFFF),
                      "\t.word\t0x%08x, 0x%08x" % (b >> 32, b & 0xFFFFFFFF),
                      "\t.word\t0x%08x, 0x%08x" % (sentinel >> 32, sentinel & 0xFFFFFFFF)]
        self.body += ["\tldil\tL%%%s+%d, %%r3" % (self.label, 32 * k),
                      "\tldo\tR%%%s+%d(%%r3), %%r3" % (self.label, 32 * k),
                      "\tldo\t16(%r3), %r4",
                      "\tfldws\t0(%r3), %fr0",             # status: RM only
                      "\tfldds\t8(%r3), %fr4",
                      "\tfldds\t0(%r4), %fr5",
                      "\tfldds\t8(%r4), %fr6",
                      "\tfldds\t8(%r4), %fr7"]
        if sgl_load:                                       # singles live in the left halves
            self.body += ["\tfldws\t8(%r3), %fr4L", "\tfldws\t0(%r4), %fr5L"]
        self.body += ["\tldi\t0, %r6"] + op_lines + ["\tldi\t1, %r6",
                      "\tfstds\t%fr6, 0(%r9)",
                      "\tfstws\t%fr0, 8(%r9)",
                      "\tstw\t%r0, 12(%r9)",
                      "\tldo\t16(%r9), %r9"]
        self.ins.append(vin)

    def finish(self):
        self.suite.add(self.name, len(self.ins), FP_WORDS, self.body, self.ins)
        self.suite.prologue += ["\t.section .rodata", "\t.align\t8", "%s:" % self.label] + \
            self.data + ["\t.text"]


def gen_fp_common(rng, name, edge):
    suite = Suite(name)
    # enable the FPU: CCR (cr10) bits for coprocessor 0 (the FPU) and its pair
    suite.setup = ["\tldi\t0xc0, %r1", "\tmtctl\t%r1, %cr10"]
    N = 10

    def operand(sgl):
        if edge:
            return rng.choice(fp_edge_values(sgl))
        x = rand_normal_double(rng, -20, 20) if rng.random() < 0.85 else \
            float(rng.choice([1, 2, 3, 10, -7, 0.5, 0.25, 1e6]))
        return f2w(x) if sgl else d2w(x)

    def pack(v, sgl):
        return (v << 32) if sgl else v

    arith = [("fadd", 2), ("fsub", 2), ("fmpy", 2), ("fdiv", 2), ("fsqrt", 1),
             ("frnd", 1), ("fabs", 1), ("fcpy", 1)]
    for op, nops in arith:
        for fmt in ("sgl", "dbl"):
            rms = range(4) if op in ("fadd", "fsub", "fmpy", "fdiv", "fsqrt", "frnd") else [0]
            for rm in rms:
                g = FpGroup(suite, "%s,%s.%s" % (op, fmt, RM_NAMES[rm]))
                for v in range(N):
                    a, b = operand(fmt == "sgl"), operand(fmt == "sgl")
                    if op == "fsqrt" and not edge:
                        a = (a & 0x7FFFFFFF) if fmt == "sgl" else (a & 0x7FFFFFFFFFFFFFFF)
                    r = ("%fr4L", "%fr5L", "%fr6L") if fmt == "sgl" else ("%fr4", "%fr5", "%fr6")
                    if nops == 2:
                        line = "\t%s,%s\t%s, %s, %s" % (op, fmt, r[0], r[1], r[2])
                    else:
                        line = "\t%s,%s\t%s, %s" % (op, fmt, r[0], r[2])
                    g.vector(rm, pack(a, fmt == "sgl"), pack(b, fmt == "sgl"),
                             0x5A5A5A5A5A5A5A5A, [line], fmt == "sgl",
                             {"a": a, "b": b, "rm": rm})
                g.finish()
    # conversions between formats and to/from fixed point
    convs = [("fcnvff", "sgl", "dbl"), ("fcnvff", "dbl", "sgl"),
             ("fcnvxf", "sgl", "sgl"), ("fcnvxf", "sgl", "dbl"),
             ("fcnvxf", "dbl", "sgl"), ("fcnvxf", "dbl", "dbl"),
             ("fcnvfx", "sgl", "sgl"), ("fcnvfx", "dbl", "sgl"),
             ("fcnvfx", "sgl", "dbl"), ("fcnvfx", "dbl", "dbl"),
             ("fcnvfxt", "sgl", "sgl"), ("fcnvfxt", "dbl", "sgl"),
             ("fcnvfxt", "sgl", "dbl"), ("fcnvfxt", "dbl", "dbl")]
    for op, sf, df in convs:
        for rm in (range(4) if op != "fcnvfxt" else [0]):
            g = FpGroup(suite, "%s,%s,%s.%s" % (op, sf, df, RM_NAMES[rm]))
            for v in range(N):
                if op == "fcnvxf":         # integer source
                    a = rng.choice([0, 1, -1, 0x7FFFFFFF, 0x80000000, rng.getrandbits(32),
                                    rng.randint(-100000, 100000) & 0xFFFFFFFF])
                    if sf == "dbl":
                        a = rng.choice([a, rng.getrandbits(64), 0x8000000000000000,
                                        (rng.randint(-10**12, 10**12)) & 0xFFFFFFFFFFFFFFFF])
                    a &= 0xFFFFFFFF if sf == "sgl" else 0xFFFFFFFFFFFFFFFF
                elif edge:
                    a = rng.choice(fp_edge_values(sf == "sgl"))
                else:                      # keep fixed-point results in range
                    x = rng.choice([-1, 1]) * rng.uniform(0, 2.0 ** rng.randint(0, 30))
                    a = f2w(x) if sf == "sgl" else d2w(x)
                src = "%fr4L" if sf == "sgl" else "%fr4"
                dst = "%fr6L" if df == "sgl" else "%fr6"
                line = "\t%s,%s,%s\t%s, %s" % (op, sf, df, src, dst)
                g.vector(rm, pack(a, sf == "sgl"), 0, 0x5A5A5A5A5A5A5A5A, [line],
                         sf == "sgl", {"a": a, "rm": rm})
            g.finish()
    # compare + test: C bit in the status, ftest nullifies on C
    conds = ["false?", "false", "?", "!<=>", "=", "=t", "?=", "!<>", "!?>=", "<", "?<",
             "!>=", "!?>", "<=", "?<=", "!>", "!?<=", ">", "?>", "!<=", "!?<", ">=", "?>=",
             "!<", "!?=", "<>", "!=", "!=t", "!?", "<=>", "true?", "true"]
    probe = [((c, f), "\tfcmp,%s,%s\t%%fr4, %%fr5" % (f, c)) for c in conds for f in ("sgl", "dbl")]
    for (c, fmt), _ in filter_valid(probe):
        g = FpGroup(suite, "fcmp,%s,%s" % (fmt, c))
        for v in range(6):
            a = operand(fmt == "sgl")
            b = a if v == 0 else operand(fmt == "sgl")
            r = ("%fr4L", "%fr5L") if fmt == "sgl" else ("%fr4", "%fr5")
            g.vector(0, pack(a, fmt == "sgl"), pack(b, fmt == "sgl"), 0x5A5A5A5A5A5A5A5A,
                     ["\tfcmp,%s,%s\t%s, %s" % (fmt, c, r[0], r[1]), "\tftest",
                      "\tfcpy,dbl\t%fr4, %fr6"],          # nullified by ftest when C
                     fmt == "sgl", {"a": a, "b": b})
        g.finish()
    if not edge:
        # fixed-point unsigned multiply in the FPU
        g = FpGroup(suite, "xmpyu")
        for v in range(16):
            a, b = rng.getrandbits(32), rng.getrandbits(32)
            g.vector(0, a << 32, b << 32, 0x5A5A5A5A5A5A5A5A,
                     ["\txmpyu\t%fr4L, %fr5L, %fr6"], True, {"a": a, "b": b})
        g.finish()
        # multiply-add/subtract: fr6 = fr4 * fr5 ; fr7 += fr4 (dbl only:
        # the sgl forms use fr16-fr31 halves)
        for op in ("fmpyadd", "fmpysub"):
            g = FpGroup(suite, "%s,dbl" % op)
            for v in range(N):
                a, b = operand(False), operand(False)
                g.vector(0, a, b, d2w(rand_normal_double(rng)),
                         ["\t%s,dbl\t%%fr4, %%fr5, %%fr6, %%fr4, %%fr7" % op,
                          "\tfcpy,dbl\t%fr7, %fr6"] if v % 2 else
                         ["\t%s,dbl\t%%fr4, %%fr5, %%fr6, %%fr4, %%fr7" % op],
                         False, {"a": a, "b": b, "which": "add-result" if v % 2 else "mpy-result"})
            g.finish()
    return suite


