# ---------------------------------------------------------------------------
# max1: the PA7100LC's MAX-1 halfword multimedia instructions (32-bit forms).
# GNU as only knows them at .level 2.0, so they are assembled there once and
# emitted as .word into the PA 1.1 ROM. QEMU refuses them on a PA 1.1 CPU
# (translate.c:3099), so the reference for this suite is tests/cpu/model.py.
# Stored per vector: result, nullify flag, carry map (as the alu suites).
# ---------------------------------------------------------------------------
def encode_level20(lines):
    """Assemble lines at .level 2.0 and return their instruction words."""
    with tempfile.TemporaryDirectory() as d:
        src, obj, binf = (os.path.join(d, n) for n in ("t.s", "t.o", "t.bin"))
        with open(src, "w") as f:
            f.write("\t.level 2.0\n\t.text\n" + "\n".join(lines) + "\n")
        subprocess.run([AS, "-o", obj, src], check=True)
        subprocess.run([AS.replace("-as", "-objcopy"), "-O", "binary", "-j", ".text", obj, binf],
                       check=True)
        data = open(binf, "rb").read()
    return [int.from_bytes(data[i:i + 4], "big") for i in range(0, len(data), 4)]


def gen_max1(rng):
    suite = Suite("max1")
    forms = [("hadd", ""), ("hadd", ",ss"), ("hadd", ",us"),
             ("hsub", ""), ("hsub", ",ss"), ("hsub", ",us"), ("havg", "")]
    words = encode_level20(["\t%s%s\t%%r3, %%r4, %%r5" % f for f in forms] +
                           ["\thshladd\t%%r3, %d, %%r4, %%r5" % sa for sa in (1, 2, 3)] +
                           ["\thshradd\t%%r3, %d, %%r4, %%r5" % sa for sa in (1, 2, 3)])
    names = ["%s%s" % f for f in forms] + ["hshladd,%d" % sa for sa in (1, 2, 3)] + \
            ["hshradd,%d" % sa for sa in (1, 2, 3)]
    halves = [0x0000, 0x0001, 0x7FFF, 0x8000, 0xFFFF, 0x8001, 0x4000, 0x00FF, 0xFF00]
    for name, word in zip(names, words):
        body, ins = [], []
        for v in range(24):
            if rng.random() < 0.5:
                a = (rng.choice(halves) << 16) | rng.choice(halves)
                b = (rng.choice(halves) << 16) | rng.choice(halves)
            else:
                a, b = rng.getrandbits(32), rng.getrandbits(32)
            body += li(3, a) + li(4, b) + CARRY_CLEAR
            body += ["\tldi\t0, %r6", "\t.word\t0x%08x\t; %s %%r3,%%r4,%%r5" % (word, name)]
            body += vec_tail()
            ins.append({"a": a, "b": b, "word": word})
        suite.add(name, 24, 3, body, ins)
    return suite


GENERATORS = {"alu1": gen_alu1, "alu2": gen_alu2, "shift": gen_shift,
              "mem": gen_mem, "branch": gen_branch, "trap": gen_trap,
              "fp": gen_fp, "fpedge": gen_fpedge, "max1": gen_max1}


def main(argv):
    if len(argv) != 3 or argv[1] not in GENERATORS:
        sys.exit(__doc__)
    rng = random.Random({"alu1": 1, "alu2": 3, "shift": 2, "mem": 4, "branch": 5, "trap": 6, "fp": 7, "fpedge": 8, "max1": 9}[argv[1]] * 0x715)
    suite = GENERATORS[argv[1]](rng)
    os.makedirs(argv[2], exist_ok=True)
    suite.write(argv[2])
    total = sum(g[2] for g in suite.groups)
    print("%s: %d groups, %d vectors" % (suite.name, len(suite.groups), total))


if __name__ == "__main__":
    main(sys.argv)
